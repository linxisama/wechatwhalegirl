# 玩梗信号里，"哈哈/笑死/开玩笑"这类是**明确**在开玩笑；而"离谱""草"单独出现
# 也可能只是叹口气、骂一句电脑。strict 模式下后者算"拿不准"，按认真处理，
# 不顺着玩梗把人家的话带偏。
PLAYFUL_EXPLICIT_MARKERS: tuple[str, ...] = (
    "哈哈", "笑死", "太逗", "开玩笑", "逗你", "玩梗", "整活", "乐死", "绷不住笑",
)

# strict 模式下"拿不准就按认真处理"用的兜底提示词（不是旧项目的段落，
# 而是把 strict 的含义写清楚：不抢着玩梗，先确认意思）。
STRICT_SERIOUS_PROMPT = (
    "\n\n【本轮语气：拿不准，按认真处理】\n"
    "这句话看不出是不是在玩梗，先当对方在认真说话：不要抢着玩梗、调侃或玩谐音。\n"
    "本轮禁止拿对方说的事当笑料，禁止说“好麻烦哦”，也不要强行逗乐。\n"
    "一到两句，语气自然；真是在开玩笑的话，下一轮再放松也不迟。"
)


def detect_mood(content: str) -> str:
    """判断当前这句话的情绪色彩；没有明显情绪就返回空字符串。

    判定顺序即优先级（见 ``MOOD_SIGNALS``）。这里做成模块级函数而不是私有方法，
    是为了让 ``computer_helper`` 也能复用同一套词表 —— 两处各写一份词表迟早会
    对不上（旧项目里就是同一个类内部的 classmethod，所以没这个问题）。
    """
    text = str(content or "").casefold()
    if not text:
        return ""
    for mood, signals in MOOD_SIGNALS:
        if any(signal in text for signal in signals):
            return mood
    return ""


class MoodGuidance(PluginBase):
    META = PluginMeta(
        id="mood_guidance",
        name="情商与情绪优先",
        category="social",
        description=(
            "按 9 类情绪（责怪/低落/生气/疲惫/孤单/道歉/被夸/道别/玩梗）判断当前这句话，"
            "把「先接住情绪、再接住事」的要求和本轮禁止项追加进系统提示词。"
            "纯本地判定，不额外调用模型；判定不出情绪时不做任何干预。"
        ),
        enabled_by_default=True,
        config_schema={
            "enabled": FieldSchema(type="bool", label="启用"),
            "strict": FieldSchema(
                type="bool", label="拿不准按认真处理",
                description=("默认开启。只说“离谱”“草”这类含糊信号时不当玩梗，"
                             "先按对方在认真说话处理，避免把别人的难受当笑料。"),
            ),
            "maxChars": FieldSchema(
                type="int", label="情绪判定的字数上限", min=20, max=2000,
                description="超过这个字数的消息不做情绪判定（长文里出现一个“难过”就改语气会误伤）。默认 200。",
            ),
        },
        default_settings={"enabled": True, "strict": True, "maxChars": 200},
    )

    def on_pre_ai(self, message, conversation, runtime):
        # 契约要求 on_pre_ai 是同步钩子且不能抛异常；本插件连 runtime 都不碰，
        # 所以出错只需要安静地放弃本轮干预。
        try:
            if not self.get("enabled", True):
                return None
            if not isinstance(message, dict):
                return None
            text = str(message.get("text", "") or "")
            if not text.strip():
                return None
            limit = int(self.get("maxChars", 200) or 200)
            if len(text) > limit:
                return None
            mood = detect_mood(text)
            if not mood:
                return None
            if mood == "playful" and self.get("strict", True):
                # strict：只有明确在开玩笑才按 playful 处理，否则当"拿不准"。
                if not any(marker in text.casefold() for marker in PLAYFUL_EXPLICIT_MARKERS):
                    mood = "serious"
            prompt = MOOD_PROMPTS.get(mood) or STRICT_SERIOUS_PROMPT
            prompt = prompt.strip()
            if not prompt:
                return None
            # extra_system 由管理器拼到系统提示词后面，这里只给"这一轮怎么说话"。
            return {"extra_system": prompt}
        except Exception:
            return None
